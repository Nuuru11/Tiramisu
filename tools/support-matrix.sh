#!/bin/bash
# tiramisu/tools/support-matrix.sh
# Generate docs/support-matrix.md from a real corpus run. Every number comes
# from test_corpus --coverage, which classifies every bound import as
# real / recorded / named-silent through trt_symbol_class(). The matrix is
# MEASURED, never hand-written.
set -uo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
cd "$here"

# Build + smoke the corpus first; this produces tests/out/test_corpus with
# the exact source set build-test.sh uses and proves the tree still binds.
tools/corpus-smoke.sh >/dev/null || exit 1

out=tests/out
mapfile -t PES < <(find corpus-local -maxdepth 2 -type f 2>/dev/null | \
  grep -iE '\.(exe|dll)$' | sort)
[[ ${#PES[@]} -gt 0 ]] || { echo "ERROR: no corpus PEs found" >&2; exit 1; }

report="$out/support-matrix.txt"
"$out/test_corpus" --coverage "${PES[@]}" >"$report" 2>&1 || exit 1

{
  echo "# Tiramisu — measured support matrix"
  echo
  echo "> Generated by \`tools/support-matrix.sh\` from \`test_corpus --coverage\`."
  echo "> Do not edit by hand. Every row is a real corpus bind simulation."
  echo
  echo "| PE | bound imports | real | recorded | named-silent | real % |"
  echo "|---|---:|---:|---:|---:|---:|"
  grep '^COVERAGE ' "$report" | grep -v '^COVERAGE SELFTEST:' | \
  while read -r _ name rest; do
    name=${name%:}
    imports=$(sed -n 's/.*imports=\([0-9]*\).*/\1/p' <<<"$rest")
    real=$(sed -n 's/.*real=\([0-9]*\).*/\1/p' <<<"$rest")
    recorded=$(sed -n 's/.*recorded=\([0-9]*\).*/\1/p' <<<"$rest")
    silent=$(sed -n 's/.*named-silent=\([0-9]*\).*/\1/p' <<<"$rest")
    pct="0"
    [[ ${imports:-0} -gt 0 ]] && \
      pct=$(awk -v r="${real:-0}" -v t="$imports" 'BEGIN{printf "%.1f", 100*r/t}')
    printf '| %s | %s | %s | %s | %s | %s%% |\n' \
      "$name" "$imports" "$real" "$recorded" "$silent" "$pct"
  done
  echo
  echo "## Totals"
  echo '```'
  grep '^COVERAGE ' "$report"
  echo '```'
  echo
  echo "**Reading the numbers:** \`real\` = real semantics; \`recorded\` = the"
  echo "call is accepted and logged but does nothing (e.g. D3D12 draws);"
  echo "\`named-silent\` = a truthful empty answer or named failure (e.g."
  echo "Media Foundation EOS with no frames, Steam auth-only answers)."
  echo "A high \`real %\` predicts a title that reaches gameplay; recorded and"
  echo "named-silent imports are the exact roadmap items for that title."
  echo
  echo "**Scope:** this walks the static import directory only. Delay imports"
  echo "(e.g. \`UnityPlayer.dll -> d3d12.dll\`) are bound by the runtime but are"
  echo "not counted here yet, so a \`recorded=0\` row does not prove D3D12 is"
  echo "unused by that title."
} >docs/support-matrix.md

echo "wrote docs/support-matrix.md"
