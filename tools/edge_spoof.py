#!/usr/bin/env python3
"""Patch a Tiramisu AppxManifest.xml to spoof the Microsoft Edge UWP identity.

This is the build-time half of the Xbox hardware-mouse experiment documented in
XBOX-MOUSE.md. It does NOT contact Microsoft or change any host code: it only
rewrites the manifest Identity/Publisher so the resulting Package Family Name is
the well-known Edge PFN:

    Microsoft.MicrosoftEdge_8wekyb3d8bbwe

The matching self-signed certificate (subject == Publisher) is generated by
tools/pack.sh in EDGE_SPOOF mode. This is for own-console Dev Mode testing only;
the identity cannot be published and may collide with a real Edge package.

Usage:
    edge_spoof.py SRC_MANIFEST DST_MANIFEST
    edge_spoof.py --print-pfn
    edge_spoof.py --cert-subj
    edge_spoof.py --check MANIFEST
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

# Exact strings from the Xbox mouse study. Windows derives PublisherId from the
# Publisher string below; for this publisher it is the well-known 8wekyb3d8bbwe.
EDGE_IDENTITY_NAME = "Microsoft.MicrosoftEdge"
EDGE_PUBLISHER = (
    "CN=Microsoft Corporation, O=Microsoft Corporation, L=Redmond, "
    "S=Washington, C=US"
)
EDGE_PUBLISHER_ID = "8wekyb3d8bbwe"
EDGE_PUBLISHER_DISPLAY = "Microsoft Corporation"
EDGE_PFN = f"{EDGE_IDENTITY_NAME}_{EDGE_PUBLISHER_ID}"

# OpenSSL uses ST for stateOrProvinceName; Windows renders the same RDN as S.
# pack.sh feeds this to `openssl req -subj`; do not use /S= here (OpenSSL drops it).
# The RDN order is REVERSED relative to the Publisher string on purpose: the
# MSIX signer/verifier walks the X.500 name from the last RDN to the first, so a
# cert built C->ST->L->O->CN is read back as "CN=..., O=..., L=..., S=..., C=US"
# and matches the manifest Publisher exactly (makemsix unpack checks this).
EDGE_CERT_SUBJ = (
    "/C=US/ST=Washington/L=Redmond/"
    "O=Microsoft Corporation/CN=Microsoft Corporation"
)

_IDENTITY_RE = re.compile(r"<Identity\b[^>]*?/>")
_PUBLISHER_DISPLAY_RE = re.compile(
    r"(<PublisherDisplayName\s*>).*?(</PublisherDisplayName\s*>)", re.S
)


def spoof_manifest(xml: str) -> str:
    """Return xml with the Identity and PublisherDisplayName rewritten."""
    if len(_IDENTITY_RE.findall(xml)) != 1:
        raise ValueError("expected exactly one self-closing <Identity .../>")
    if len(_PUBLISHER_DISPLAY_RE.findall(xml)) != 1:
        raise ValueError("expected exactly one <PublisherDisplayName>")

    def repl_identity(match: re.Match[str]) -> str:
        tag = match.group(0)
        # Replace only the two attributes that determine the PFN. Keep Version,
        # ProcessorArchitecture and every other attribute byte-for-byte.
        tag, n1 = re.subn(
            r'(\bName\s*=\s*)"[^"]*"',
            rf'\1"{EDGE_IDENTITY_NAME}"',
            tag,
            count=1,
        )
        tag, n2 = re.subn(
            r'(\bPublisher\s*=\s*)"[^"]*"',
            rf'\1"{EDGE_PUBLISHER}"',
            tag,
            count=1,
        )
        if n1 != 1 or n2 != 1:
            raise ValueError("Identity tag is missing Name= or Publisher=")
        return tag

    xml = _IDENTITY_RE.sub(repl_identity, xml, count=1)
    xml = _PUBLISHER_DISPLAY_RE.sub(
        lambda m: f"{m.group(1)}{EDGE_PUBLISHER_DISPLAY}{m.group(2)}", xml, count=1
    )
    return xml


def check_manifest(xml: str) -> None:
    """Fail if the manifest does not carry the Edge identity."""
    identity = _IDENTITY_RE.search(xml)
    if not identity:
        raise ValueError("no <Identity .../> in manifest")
    attrs = identity.group(0)
    if f'Name="{EDGE_IDENTITY_NAME}"' not in attrs:
        raise ValueError(f"Identity Name is not {EDGE_IDENTITY_NAME}")
    if f'Publisher="{EDGE_PUBLISHER}"' not in attrs:
        raise ValueError("Identity Publisher is not the Microsoft string")
    display = _PUBLISHER_DISPLAY_RE.search(xml)
    if not display or EDGE_PUBLISHER_DISPLAY not in display.group(0):
        raise ValueError("PublisherDisplayName is not Microsoft Corporation")


def main(argv: list[str]) -> int:
    if argv == ["--print-pfn"]:
        print(EDGE_PFN)
        return 0
    if argv == ["--cert-subj"]:
        print(EDGE_CERT_SUBJ)
        return 0
    if len(argv) == 2 and argv[0] == "--check":
        try:
            check_manifest(Path(argv[1]).read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            print(f"NOT spoofed: {exc}", file=sys.stderr)
            return 1
        print(f"Edge identity OK: {EDGE_PFN}")
        return 0
    if len(argv) == 2:
        src, dst = Path(argv[0]), Path(argv[1])
        try:
            xml = spoof_manifest(src.read_text(encoding="utf-8"))
            check_manifest(xml)
        except (OSError, ValueError) as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 1
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(xml, encoding="utf-8")
        print(f"Edge-spoofed manifest: {dst}")
        print(f"PFN: {EDGE_PFN}")
        return 0
    print(__doc__.strip(), file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
